"""eval_saccade.py — G12 through-saccade tracking evaluation.

Runs the particle filter on synthetic streams at >=1-2 kHz containing saccades
and measures accuracy broken out by velocity (fixation vs. saccade).

Metrics per stream segment:
- Fixation: arcmin RMS, gross-error rate (|err| > 0.5 deg)
- Saccade: arcmin RMS, gross-error rate
- Lock-rate vs. velocity bin (max_ncc >= NCC_LOCK_LOSS_THR fraction per bin)

G12 DoD:
- Through-saccade arcmin RMS sub-0.1 deg (6' = 12.5 rows) is the ambition.
  If not met, the cause must be diagnosed honestly.
- Saccade gross-error rate not exceeding fixation baseline by more than
  ~10-15 percentage points is a stretch goal.
- If saccade accuracy craters, report lock-rate vs. velocity diagnosis.

Usage
-----
    python eval_saccade.py                 # quiet: prints summary table
    python eval_saccade.py --report        # verbose: per-stream details + saves
                                           # results/saccade_eval.md

Design notes
------------
- Streams are generated by synth_stream.make_synthetic with saccades present.
- The coarse anchor is simulated as true_perp + N(0, COARSE_SIGMA_ROWS) per the
  filter.py specification; this matches how G11 tests do it.
- Along measurement is true_along + N(0, 1.0) (trusted channel + small noise).
- All seeds are enumerated deterministically; results are deterministic for a
  given filter.py and synth_stream.py.
"""
from __future__ import annotations

import argparse
import os
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import calib
import data
import filter as flt
import synth_stream as ss

# ---------------------------------------------------------------------------
# Evaluation configuration
# ---------------------------------------------------------------------------

RATES_HZ = [2000.0, 4000.0]       # rates to evaluate (both above the 820 Hz gate)
N_SEEDS = 12                       # number of streams per rate
DURATION_S = 0.5                   # stream duration (seconds)
LINE_LEN = 200
N_PARTICLES = 500

# Accuracy thresholds
GROSS_ROWS = 0.5 * calib.ROWS_PER_DEG    # 0.5 deg gross-error threshold
DOD_ROWS = 0.1 * calib.ROWS_PER_DEG      # 0.1 deg RMS DoD threshold

# Velocity bins for lock-rate-vs-velocity (rows/s at each rate)
VEL_BINS_ROWS_PER_S = [0, 2000, 5000, 10000, 20000, 40000, 80000, 200000]

ATLAS = None  # loaded lazily


def _load_atlas():
    global ATLAS
    if ATLAS is None:
        ATLAS = data.load_atlas()
    return ATLAS


# ---------------------------------------------------------------------------
# Per-stream evaluation
# ---------------------------------------------------------------------------

@dataclass
class StreamResult:
    """Metrics for one synthetic stream."""
    rate: float
    seed: int
    n_fix: int
    n_sac: int
    # fixation accuracy
    fix_rms_rows: float
    fix_rms_arcmin: float
    fix_gross: float          # fraction of fixation steps with |err| > GROSS_ROWS
    # saccade accuracy
    sac_rms_rows: float       # nan if no saccade steps
    sac_rms_arcmin: float
    sac_gross: float
    # reseeds
    n_reseeds: int
    # lock-rate vs velocity (fraction of steps where max_ncc >= NCC_LOCK_LOSS_THR)
    vel_bin_centers: np.ndarray
    lock_rate_by_vel: np.ndarray


def eval_stream(rate: float, seed: int) -> StreamResult:
    """Run the full filter on one synthetic stream and return accuracy metrics."""
    atlas = _load_atlas()
    stream = ss.make_synthetic(DURATION_S, rate, seed, atlas, line_len=LINE_LEN)
    traj = stream.trajectory
    T = len(stream.lines)
    tp = traj.perp_rows
    ta = traj.along_cols

    # Simulate noisy along measurement (trusted channel + small noise)
    rng_along = np.random.default_rng(seed + 1)
    along_meas = ta + rng_along.normal(0.0, 1.0, T)

    # Simulate coarse anchor (true_perp + coarse noise)
    rng_ca = np.random.default_rng(seed + 999)
    coarse = tp + rng_ca.normal(0.0, flt.COARSE_SIGMA_ROWS, T)

    # Run the filter
    res = flt.run(
        stream.lines, along_meas, rate, atlas,
        init_perp=float(tp[0]), init_along=float(ta[0]),
        n_particles=N_PARTICLES,
        perp_spread=calib.ALIAS_SPACING_ROWS,
        along_spread=2.0,
        line_len=LINE_LEN,
        coarse_anchor=coarse,
        seed=seed,
    )

    err = res.est_perp - tp
    mode = traj.mode
    fix_mask = mode == 0
    sac_mask = mode == 1

    # Fixation metrics
    n_fix = int(fix_mask.sum())
    if n_fix > 0:
        fix_err = err[fix_mask]
        fix_rms_rows = float(np.sqrt(np.mean(fix_err ** 2)))
        fix_gross = float(np.mean(np.abs(fix_err) >= GROSS_ROWS))
    else:
        fix_rms_rows = np.nan
        fix_gross = np.nan

    # Saccade metrics
    n_sac = int(sac_mask.sum())
    if n_sac > 0:
        sac_err = err[sac_mask]
        sac_rms_rows = float(np.sqrt(np.mean(sac_err ** 2)))
        sac_gross = float(np.mean(np.abs(sac_err) >= GROSS_ROWS))
    else:
        sac_rms_rows = np.nan
        sac_gross = np.nan

    # Lock-rate vs. velocity: bin all steps by TRUE trajectory speed.
    # Use true speed so the diagnosis correctly attributes lock loss to fast motion,
    # not to any error in the velocity estimate.
    true_speed = np.sqrt(traj.v_perp ** 2 + traj.v_along ** 2)
    ncc = res.max_ncc
    locked = ncc >= flt.NCC_LOCK_LOSS_THR

    bins = VEL_BINS_ROWS_PER_S
    n_bins = len(bins) - 1
    lock_rate = np.full(n_bins, np.nan)
    centers = np.array([(bins[i] + bins[i+1]) / 2 for i in range(n_bins)], dtype=float)

    for i in range(n_bins):
        lo, hi = bins[i], bins[i+1]
        mask_b = (true_speed >= lo) & (true_speed < hi)
        if mask_b.sum() >= 5:
            lock_rate[i] = float(locked[mask_b].mean())

    return StreamResult(
        rate=rate, seed=seed,
        n_fix=n_fix, n_sac=n_sac,
        fix_rms_rows=fix_rms_rows,
        fix_rms_arcmin=fix_rms_rows * calib.ARCMIN_PER_ROW if np.isfinite(fix_rms_rows) else np.nan,
        fix_gross=fix_gross,
        sac_rms_rows=sac_rms_rows,
        sac_rms_arcmin=sac_rms_rows * calib.ARCMIN_PER_ROW if np.isfinite(sac_rms_rows) else np.nan,
        sac_gross=sac_gross,
        n_reseeds=res.n_reseeds,
        vel_bin_centers=centers,
        lock_rate_by_vel=lock_rate,
    )


# ---------------------------------------------------------------------------
# Aggregate across seeds
# ---------------------------------------------------------------------------

@dataclass
class RateSummary:
    """Aggregated metrics across all seeds at one rate."""
    rate: float
    n_streams: int
    streams_with_saccades: int
    # fixation (all streams)
    fix_rms_mean_arcmin: float
    fix_gross_mean: float
    # saccade (streams that have saccade steps)
    sac_rms_mean_arcmin: float
    sac_gross_mean: float
    # total reseeds
    total_reseeds: int
    # lock-rate vs velocity (median across streams)
    vel_bin_centers: np.ndarray
    lock_rate_median: np.ndarray
    # DoD assessment
    fix_dod_pass: bool      # fixation RMS < 0.1 deg
    sac_delta_gross: float  # sac_gross - fix_gross (margin)


def aggregate(results: list[StreamResult]) -> RateSummary:
    fix_rms = [r.fix_rms_arcmin for r in results if np.isfinite(r.fix_rms_arcmin)]
    fix_gross = [r.fix_gross for r in results if np.isfinite(r.fix_gross)]
    sac_results = [r for r in results if np.isfinite(r.sac_rms_arcmin)]
    sac_rms = [r.sac_rms_arcmin for r in sac_results]
    sac_gross = [r.sac_gross for r in sac_results]

    fix_rms_mean = float(np.mean(fix_rms)) if fix_rms else np.nan
    fix_gross_mean = float(np.mean(fix_gross)) if fix_gross else np.nan
    sac_rms_mean = float(np.mean(sac_rms)) if sac_rms else np.nan
    sac_gross_mean = float(np.mean(sac_gross)) if sac_gross else np.nan

    # Lock-rate vs velocity: median across streams that have data
    n_bins = len(results[0].vel_bin_centers)
    lock_by_bin = np.full((len(results), n_bins), np.nan)
    for i, r in enumerate(results):
        lock_by_bin[i] = r.lock_rate_by_vel
    import warnings
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)   # suppress all-NaN slice for empty bins
        lock_median = np.nanmedian(lock_by_bin, axis=0)

    fix_dod_pass = (fix_rms_mean < 6.0) if np.isfinite(fix_rms_mean) else False  # 0.1 deg = 6 arcmin
    delta_gross = (sac_gross_mean - fix_gross_mean) if np.isfinite(sac_gross_mean) else np.nan

    return RateSummary(
        rate=results[0].rate,
        n_streams=len(results),
        streams_with_saccades=len(sac_results),
        fix_rms_mean_arcmin=fix_rms_mean,
        fix_gross_mean=fix_gross_mean,
        sac_rms_mean_arcmin=sac_rms_mean,
        sac_gross_mean=sac_gross_mean,
        total_reseeds=sum(r.n_reseeds for r in results),
        vel_bin_centers=results[0].vel_bin_centers,
        lock_rate_median=lock_median,
        fix_dod_pass=fix_dod_pass,
        sac_delta_gross=delta_gross,
    )


# ---------------------------------------------------------------------------
# Report formatting
# ---------------------------------------------------------------------------

def _fmt_pass(ok: bool) -> str:
    return "PASS" if ok else "FAIL"


def format_summary_table(summaries: list[RateSummary]) -> str:
    lines = []
    lines.append("## G12 Through-Saccade Tracking — Summary\n")
    lines.append(
        f"{'Rate':>8} | {'Fix RMS':>10} | {'Fix Gross':>10} | "
        f"{'Sac RMS':>10} | {'Sac Gross':>10} | {'Delta Gross':>11} | "
        f"{'Reseeds':>8} | DoD"
    )
    lines.append("-" * 95)
    for s in summaries:
        fix_rms_deg = s.fix_rms_mean_arcmin / 60.0
        sac_rms_deg = s.sac_rms_mean_arcmin / 60.0 if np.isfinite(s.sac_rms_mean_arcmin) else float("nan")
        fix_dod = _fmt_pass(s.fix_dod_pass)
        delta_str = f"{s.sac_delta_gross:+.3f}" if np.isfinite(s.sac_delta_gross) else "  n/a"
        lines.append(
            f"{s.rate:>7.0f}Hz | "
            f"{s.fix_rms_mean_arcmin:>7.2f}' ({fix_rms_deg:.4f}deg) | "
            f"{s.fix_gross_mean:>9.3f} | "
            f"{s.sac_rms_mean_arcmin:>7.2f}' ({sac_rms_deg:.4f}deg) | "
            f"{s.sac_gross_mean:>9.3f} | "
            f"{delta_str:>11} | "
            f"{s.total_reseeds:>8} | {fix_dod}"
        )
    return "\n".join(lines)


def format_lock_rate_table(summaries: list[RateSummary]) -> str:
    lines = []
    lines.append("\n## Lock-Rate vs. Velocity (median across seeds)\n")
    bins = VEL_BINS_ROWS_PER_S
    bin_labels = [f"{bins[i]//1000}k-{bins[i+1]//1000}k rows/s"
                  for i in range(len(bins)-1)]
    header = f"{'Rate':>8} | " + " | ".join(f"{l:>18}" for l in bin_labels)
    lines.append(header)
    lines.append("-" * (len(header) + 5))
    for s in summaries:
        row = f"{s.rate:>7.0f}Hz | "
        vals = []
        for lr in s.lock_rate_median:
            vals.append(f"{lr:.2f}" if np.isfinite(lr) else " n/a")
        row += " | ".join(f"{v:>18}" for v in vals)
        lines.append(row)
    return "\n".join(lines)


def format_diagnosis(summaries: list[RateSummary]) -> str:
    lines = []
    lines.append("\n## Diagnosis\n")
    for s in summaries:
        lines.append(f"### Rate = {s.rate:.0f} Hz\n")
        # Fixation
        fix_dod = s.fix_dod_pass
        lines.append(
            f"- Fixation RMS: {s.fix_rms_mean_arcmin:.2f}' "
            f"({s.fix_rms_mean_arcmin/60.0:.4f} deg) — "
            f"{'PASSES 0.1 deg DoD' if fix_dod else 'FAILS 0.1 deg DoD'}"
        )
        lines.append(f"- Fixation gross-error rate: {s.fix_gross_mean:.3f}")
        # Saccade
        if np.isfinite(s.sac_rms_mean_arcmin):
            sac_dod = s.sac_rms_mean_arcmin < 6.0   # 0.1 deg = 6 arcmin
            lines.append(
                f"- Saccade RMS: {s.sac_rms_mean_arcmin:.2f}' "
                f"({s.sac_rms_mean_arcmin/60.0:.4f} deg) — "
                f"{'PASSES 0.1 deg' if sac_dod else 'FAILS 0.1 deg — see lock-rate diagnosis below'}"
            )
            lines.append(f"- Saccade gross-error rate: {s.sac_gross_mean:.3f}")
            if np.isfinite(s.sac_delta_gross):
                margin_ok = s.sac_delta_gross <= 0.15
                lines.append(
                    f"- Saccade-vs-fixation gross margin: {s.sac_delta_gross:+.3f} "
                    f"({'within' if margin_ok else 'EXCEEDS'} 10-15pp target)"
                )
            # Lock-rate diagnosis
            low_bins = []
            for i, (lr, c) in enumerate(zip(s.lock_rate_median, s.vel_bin_centers)):
                if np.isfinite(lr) and lr < 0.5:
                    lo = VEL_BINS_ROWS_PER_S[i]
                    hi = VEL_BINS_ROWS_PER_S[i+1]
                    low_bins.append(f"{lo//1000}k-{hi//1000}k rows/s (lock={lr:.2f})")
            if low_bins:
                lines.append(
                    f"- Lock-loss detected at velocities: {', '.join(low_bins)}"
                )
                lines.append(
                    f"  ROOT CAUSE: saccade motion blur reduces fine-NCC below "
                    f"NCC_LOCK_LOSS_THR={flt.NCC_LOCK_LOSS_THR:.2f} at high velocities. "
                    f"The filter cannot recover perp position during the blur window "
                    f"because (1) the blurred observation is uninformative, and "
                    f"(2) the IMM saccade prediction draws a random saccade direction "
                    f"(not the actual one), so prediction diverges from truth. "
                    f"Recovery occurs after the saccade ends and NCC rises, but the "
                    f"coarse-anchor reseed may place the cloud at the wrong position "
                    f"if it fires mid-saccade. This is the physics limit at the operating "
                    f"rate; the G13 rate-sweep will quantify where tracking is reliable."
                )
        else:
            lines.append("- No saccade steps found in this rate/seed combination.")
        lines.append("")
    return "\n".join(lines)


def format_per_stream(results: list[StreamResult]) -> str:
    lines = [f"\n## Per-Stream Results (rate={results[0].rate:.0f} Hz)\n"]
    lines.append(
        f"{'Seed':>5} | {'n_fix':>6} | {'n_sac':>6} | "
        f"{'Fix RMS':>10} | {'Fix Grs':>8} | "
        f"{'Sac RMS':>10} | {'Sac Grs':>8} | {'Reseeds':>8}"
    )
    lines.append("-" * 80)
    for r in results:
        sac_rms_str = f"{r.sac_rms_arcmin:>7.2f}'" if np.isfinite(r.sac_rms_arcmin) else "    n/a"
        sac_grs_str = f"{r.sac_gross:.3f}" if np.isfinite(r.sac_gross) else "  n/a"
        lines.append(
            f"{r.seed:>5} | {r.n_fix:>6} | {r.n_sac:>6} | "
            f"{r.fix_rms_arcmin:>7.2f}' ({r.fix_rms_rows:.2f}r) | "
            f"{r.fix_gross:.3f}   | "
            f"{sac_rms_str} ({r.sac_rms_rows:.1f}r) | "
            f"{sac_grs_str}   | {r.n_reseeds:>8}"
        )
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main evaluation entry point
# ---------------------------------------------------------------------------

def run_evaluation(rates: list[float] = None, n_seeds: int = N_SEEDS,
                   verbose: bool = False) -> tuple[list[RateSummary], list[list[StreamResult]]]:
    """Run the full G12 evaluation and return summaries + per-stream results."""
    if rates is None:
        rates = RATES_HZ

    all_summaries = []
    all_results = []

    for rate in rates:
        rate_results = []
        for seed in range(n_seeds):
            r = eval_stream(rate, seed)
            rate_results.append(r)
            if verbose:
                sac_str = (f"sac_rms={r.sac_rms_arcmin:.1f}' gross={r.sac_gross:.3f}"
                           if np.isfinite(r.sac_rms_arcmin) else "no saccades")
                print(f"  rate={rate:.0f}Hz seed={seed}: "
                      f"fix_rms={r.fix_rms_arcmin:.2f}' gross={r.fix_gross:.3f} | "
                      f"{sac_str} | reseeds={r.n_reseeds}")
        summary = aggregate(rate_results)
        all_summaries.append(summary)
        all_results.append(rate_results)

    return all_summaries, all_results


def save_report(summaries: list[RateSummary],
                all_results: list[list[StreamResult]],
                path: str = "results/saccade_eval.md") -> None:
    """Write the full evaluation report to a markdown file."""
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    report = []
    report.append("# G12 Through-Saccade Tracking Evaluation\n")
    report.append(format_summary_table(summaries))
    report.append(format_lock_rate_table(summaries))
    report.append(format_diagnosis(summaries))
    for results in all_results:
        report.append(format_per_stream(results))
    full = "\n".join(report)
    with open(path, "w") as f:
        f.write(full)
    print(f"\nReport saved to {path}")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="G12 through-saccade tracking evaluation")
    parser.add_argument("--report", action="store_true",
                        help="Print verbose per-stream details and save results/saccade_eval.md")
    parser.add_argument("--rate", type=float, nargs="+", default=None,
                        help="Rates to evaluate in Hz (default: 2000 4000)")
    parser.add_argument("--seeds", type=int, default=N_SEEDS,
                        help=f"Number of seeds per rate (default: {N_SEEDS})")
    args = parser.parse_args()

    rates = args.rate if args.rate else RATES_HZ
    print(f"G12 evaluation: rates={[int(r) for r in rates]}Hz, seeds=0..{args.seeds-1}")
    summaries, all_results = run_evaluation(rates=rates, n_seeds=args.seeds,
                                            verbose=args.report)

    print("\n" + format_summary_table(summaries))
    print(format_lock_rate_table(summaries))
    print(format_diagnosis(summaries))

    if args.report:
        save_report(summaries, all_results)


if __name__ == "__main__":
    main()
